#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# postgres-tunnel.sh — a throwaway PostgreSQL bench for Module 6b (Option A)
#
# One session, one laptop: Postgres + pgweb in containers, exposed through a
# Cloudflare tunnel. Students open a URL, log in with a per-pod database and
# password, and never install a database client.
#
# Quick start (instructor laptop, Linux/macOS; Windows: use WSL):
#
#   ./postgres-tunnel.sh up db.example.com     # your own (sub-)domain
#   ./postgres-tunnel.sh up --quick            # no domain: random trycloudflare URL
#   ./postgres-tunnel.sh status
#   ./postgres-tunnel.sh down                  # stop everything, delete the tunnel
#
# The first `up` with a domain runs `cloudflared tunnel login`, which opens a
# browser once and stores a certificate in ~/.cloudflared/. Nothing else asks
# for credentials interactively.
#
# What you get:
#   - Postgres 17 and pgweb on localhost only (private by default)
#   - one database + one role per pod (pod01 … pod20), random passwords
#   - pgweb behind HTTP basic auth
#   - a table of credentials in <state>/credentials.txt (mode 0600)
#
# This is deliberately temporary: `down` removes the containers, the volume and
# the tunnel. Do not use it for data you want to keep.
#
# Options:
#   --domain HOST     your (sub-)domain, e.g. db.example.com (the first `up` logs in via browser)
#   --quick           no domain: a random *.trycloudflare.com URL (throwaway)
#   --pods N          number of pods (default 20)
#   --lan             also publish pgweb on the LAN (classroom access without tunnel)
#   --user NAME       pgweb basic-auth user (default: class)
#   --pass PASS       pgweb basic-auth password (default: generated)
#   --dry-run         write the compose file and print the commands, start nothing
#   --yes             do not ask for confirmation before replacing an existing setup
#
# Requirements: cloudflared; podman compose, docker compose, or podman-compose.
# ---------------------------------------------------------------------------
set -euo pipefail

PROG="$(basename "$0")"
PROJECT="dbs-pg-bench"
STATE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/dbs-postgres-bench"
COMPOSE_FILE="$STATE_DIR/docker-compose.yml"
STATE_FILE="$STATE_DIR/state.env"
CRED_FILE="$STATE_DIR/credentials.txt"
TUNNEL_LOG="$STATE_DIR/tunnel.log"
TUNNEL_CONFIG="$STATE_DIR/config.yml"

PODS=20
LAN=0
DRY_RUN=0
ASSUME_YES=0
DOMAIN=""
QUICK=0
PGWEB_USER="class"
PGWEB_PASS=""

umask 077

die() { printf 'error: %s\n' "$*" >&2; exit 1; }
say() { printf '%s\n' "$*"; }
step() { printf '\n== %s\n' "$*"; }

usage() {
    awk 'NR > 2 && /^# -{10,}$/ { exit } NR > 2 { sub(/^# ?/, ""); print }' "$0"
    exit "${1:-0}"
}

gen_pw() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 8
    else
        LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 16 || true
    fi
}

need_cloudflared() {
    command -v cloudflared >/dev/null 2>&1 || die \
        "cloudflared not found. Install it: https://developers.cloudflare.com/cloudflare-one/connections/connect-networks/downloads/"
}

detect_compose() {
    if command -v podman >/dev/null 2>&1 && podman compose version >/dev/null 2>&1; then
        COMPOSE_KIND="podman"
    elif command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
        COMPOSE_KIND="docker"
    elif command -v podman-compose >/dev/null 2>&1; then
        COMPOSE_KIND="podman-compose"
    else
        die "need 'podman compose', 'docker compose', or 'podman-compose'"
    fi
}

compose() {
    case "$COMPOSE_KIND" in
        podman)         podman compose -p "$PROJECT" -f "$COMPOSE_FILE" "$@" ;;
        docker)         docker compose -p "$PROJECT" -f "$COMPOSE_FILE" "$@" ;;
        podman-compose) podman-compose -p "$PROJECT" -f "$COMPOSE_FILE" "$@" ;;
    esac
}

is_running() { [ -f "$STATE_FILE" ] && grep -q '^RUNNING=1$' "$STATE_FILE"; }

load_state() { [ -f "$STATE_FILE" ] && . "$STATE_FILE"; }

write_compose() {
    local bind="127.0.0.1"
    [ "$LAN" -eq 1 ] && bind="0.0.0.0"
    mkdir -p "$STATE_DIR"
    cat > "$COMPOSE_FILE" <<EOF
# generated by $PROG — one throwaway bench, nothing published except pgweb
services:
  db:
    image: postgres:17
    environment:
      POSTGRES_PASSWORD: "$DB_SUPER_PASSWORD"
    command:
      - postgres
      - -c
      - max_connections=200
      - -c
      - shared_buffers=256MB
      - -c
      - work_mem=8MB
    volumes:
      - pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres"]
      interval: 2s
      timeout: 3s
      retries: 30
  web:
    image: sosedoff/pgweb
    environment:
      PGWEB_AUTH_USER: "$PGWEB_USER"
      PGWEB_AUTH_PASS: "$PGWEB_PASS"
      PGWEB_SESSIONS: "1"        # one database session per browser, not one shared connection
    ports:
      - "$bind:8081:8081"
    depends_on:
      db:
        condition: service_healthy
volumes:
  pgdata:
EOF
}

start_containers() {
    detect_compose
    write_compose
    if [ "$DRY_RUN" -eq 1 ]; then
        say "would run: $COMPOSE_KIND compose -p $PROJECT up -d"
        sed 's/^/    /' "$COMPOSE_FILE"
        return 0
    fi
    compose up -d
    step "waiting for postgres"
    local i
    for i in $(seq 1 60); do
        if compose exec -T db pg_isready -U postgres >/dev/null 2>&1; then
            say "postgres is ready"
            return 0
        fi
        sleep 1
    done
    die "postgres did not become ready in 60 s — check: $COMPOSE_KIND logs"
}

create_pods() {
    local i n db pw out
    : > "$CRED_FILE"
    printf '%-8s %-10s %-10s %-18s %s\n' "# POD" "DATABASE" "USER" "PASSWORD" "CONNECTION URL" >> "$CRED_FILE"

    step "creating $PODS pod databases"
    for i in $(seq 1 "$PODS"); do
        n="$(printf '%02d' "$i")"
        db="pod$n"
        pw="$(gen_pw)"
        if [ "$DRY_RUN" -eq 1 ]; then
            say "would create role/database $db"
            printf '%-8s %-10s %-10s %-18s %s\n' "pod$n" "$db" "$db" "$pw" \
                "postgres://$db:$pw@db:5432/$db?sslmode=disable" >> "$CRED_FILE"
            continue
        fi
        out="$(compose exec -T db psql -U postgres -tAc "SELECT 1 FROM pg_roles WHERE rolname = '$db'")"
        if [ "$out" = "1" ]; then
            compose exec -T db psql -U postgres -v ON_ERROR_STOP=1 \
                -c "ALTER ROLE $db WITH PASSWORD '$pw';" >/dev/null
        else
            compose exec -T db psql -U postgres -v ON_ERROR_STOP=1 \
                -c "CREATE ROLE $db LOGIN PASSWORD '$pw';" >/dev/null
        fi
        out="$(compose exec -T db psql -U postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '$db'")"
        if [ "$out" != "1" ]; then
            compose exec -T db psql -U postgres -v ON_ERROR_STOP=1 \
                -c "CREATE DATABASE $db OWNER $db;" >/dev/null
        fi
        printf '%-8s %-10s %-10s %-18s %s\n' "pod$n" "$db" "$db" "$pw" \
            "postgres://$db:$pw@db:5432/$db?sslmode=disable" >> "$CRED_FILE"
    done
}

open_named_tunnel() {
    step "cloudflare tunnel for $DOMAIN"
    if [ "$DRY_RUN" -eq 1 ]; then
        say "would run: cloudflared tunnel login            (only if ~/.cloudflared/cert.pem is missing)"
        say "would run: cloudflared tunnel create dbs-bench-<timestamp>"
        say "would run: cloudflared tunnel route dns <name> $DOMAIN"
        say "would run: cloudflared tunnel --config $TUNNEL_CONFIG run <id>"
        TUNNEL_NAME="dbs-bench-<timestamp>"
        return 0
    fi
    need_cloudflared
    if [ ! -f "$HOME/.cloudflared/cert.pem" ]; then
        say "cloudflared needs a one-time browser login (opens now)…"
        cloudflared tunnel login
    fi

    TUNNEL_NAME="dbs-bench-$(date +%Y%m%d-%H%M%S)"
    step "creating cloudflare tunnel $TUNNEL_NAME"
    local out
    out="$(cloudflared tunnel create "$TUNNEL_NAME")"
    say "$out"
    TUNNEL_ID="$(printf '%s\n' "$out" | sed -n 's/.*with id \([0-9a-f][0-9a-f-]*\).*/\1/p' | head -n 1)"
    [ -n "${TUNNEL_ID:-}" ] || die "could not parse the tunnel id from: $out"

    cat > "$TUNNEL_CONFIG" <<EOF
tunnel: $TUNNEL_ID
credentials-file: $HOME/.cloudflared/$TUNNEL_ID.json
ingress:
  - hostname: $DOMAIN
    service: http://localhost:8081
  - service: http_status:404
EOF

    step "routing $DOMAIN to the tunnel"
    if ! cloudflared tunnel route dns "$TUNNEL_NAME" "$DOMAIN"; then
        die "could not create the DNS route for $DOMAIN — is the zone in this Cloudflare account?"
    fi

    if [ "$DRY_RUN" -eq 1 ]; then
        say "would run: cloudflared tunnel --config $TUNNEL_CONFIG run $TUNNEL_ID"
        return 0
    fi
    nohup cloudflared tunnel --config "$TUNNEL_CONFIG" run "$TUNNEL_ID" \
        >"$TUNNEL_LOG" 2>&1 &
    TUNNEL_PID=$!
    URL="https://$DOMAIN"
}

open_quick_tunnel() {
    [ "$DRY_RUN" -eq 1 ] || need_cloudflared
    step "opening a quick tunnel (random trycloudflare.com URL)"
    if [ "$DRY_RUN" -eq 1 ]; then
        say "would run: cloudflared tunnel --url http://localhost:8081 --no-autoupdate"
        URL="https://<random>.trycloudflare.com"
        return 0
    fi
    nohup cloudflared tunnel --url http://localhost:8081 --no-autoupdate \
        >"$TUNNEL_LOG" 2>&1 &
    TUNNEL_PID=$!
    local i
    URL=""
    for i in $(seq 1 30); do
        URL="$(grep -Eo 'https://[a-z0-9-]+\.trycloudflare\.com' "$TUNNEL_LOG" | head -n 1 || true)"
        [ -n "$URL" ] && break
        sleep 1
    done
    [ -n "$URL" ] || die "cloudflared did not print a URL — see $TUNNEL_LOG"
}

print_summary() {
    local lan_ip
    lan_ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
    [ -n "${lan_ip:-}" ] || lan_ip="<your-lan-ip>"

    step "ready"
    say "  URL          : $URL"
    say "  pgweb login  : $PGWEB_USER / $PGWEB_PASS"
    if [ "$LAN" -eq 1 ]; then
        say "  LAN URL      : http://$lan_ip:8081  (same pgweb login)"
    else
        say "  bind         : localhost only (use --lan for classroom access without the tunnel)"
    fi
    say "  credentials  : $CRED_FILE"
    say ""
    column -t "$CRED_FILE" 2>/dev/null || cat "$CRED_FILE"
    say ""
    say "Students: open the URL, log in to pgweb with the shared login,"
    say "then paste their connection URL from the table (host 'db', port 5432,"
    say "database/user = podNN, password from the table)."
    say ""
    say "Stop everything with: $PROG down"
}

teardown() {
    if [ ! -f "$STATE_FILE" ]; then
        say "nothing to stop in $STATE_DIR"
        return 0
    fi
    load_state

    if [ -n "${TUNNEL_PID:-}" ] && kill -0 "$TUNNEL_PID" 2>/dev/null; then
        step "stopping cloudflared"
        kill "$TUNNEL_PID" 2>/dev/null || true
        wait "$TUNNEL_PID" 2>/dev/null || true
    fi

    if [ -f "$COMPOSE_FILE" ]; then
        detect_compose
        step "removing containers and volume"
        compose down -v >/dev/null 2>&1 || true
    fi

    if [ "${MODE:-}" = "named" ] && [ -n "${TUNNEL_NAME:-}" ]; then
        step "deleting tunnel $TUNNEL_NAME"
        cloudflared tunnel delete --force "$TUNNEL_NAME" >/dev/null 2>&1 || true
        [ -n "${TUNNEL_ID:-}" ] && rm -f "$HOME/.cloudflared/$TUNNEL_ID.json"
        say "  DNS record for ${DOMAIN:-<host>} is not deleted automatically —"
        say "  remove the CNAME in the Cloudflare dashboard when you are done."
    fi

    rm -f "$STATE_FILE" "$COMPOSE_FILE" "$TUNNEL_CONFIG"
    say "stopped. Credentials kept in $CRED_FILE (delete it when the term is over)."
}

cmd_up() {
    [ "$DRY_RUN" -eq 1 ] || need_cloudflared
    if is_running && [ "$ASSUME_YES" -ne 1 ]; then
        die "a bench is already running in $STATE_DIR — run '$PROG down' first, or pass --yes"
    fi

    [ -n "$PGWEB_PASS" ] || PGWEB_PASS="$(gen_pw)"
    DB_SUPER_PASSWORD="$(gen_pw)"

    mkdir -p "$STATE_DIR"

    if [ "$DRY_RUN" -eq 0 ]; then
        start_containers
        create_pods
    else
        write_compose
        say "would write: $COMPOSE_FILE"
        sed 's/^/    /' "$COMPOSE_FILE"
        create_pods
        say "would write credentials to $CRED_FILE"
        cat "$CRED_FILE"
    fi

    if [ "$QUICK" -eq 1 ]; then
        MODE="quick"
        open_quick_tunnel
    else
        MODE="named"
        open_named_tunnel
    fi

    if [ "$DRY_RUN" -eq 0 ]; then
        {
            echo "RUNNING=1"
            echo "MODE=$MODE"
            echo "URL=${URL:-https://$DOMAIN}"
            echo "DOMAIN=${DOMAIN:-}"
            echo "TUNNEL_NAME=${TUNNEL_NAME:-}"
            echo "TUNNEL_ID=${TUNNEL_ID:-}"
            echo "TUNNEL_PID=${TUNNEL_PID:-}"
            echo "PGWEB_USER=$PGWEB_USER"
            echo "PGWEB_PASS=$PGWEB_PASS"
        } > "$STATE_FILE"
        print_summary
    fi
}

cmd_status() {
    if [ ! -f "$STATE_FILE" ]; then
        say "no bench in $STATE_DIR"
        return 0
    fi
    load_state
    say "mode     : ${MODE:-?}"
    say "url      : ${URL:-?}"
    say "pgweb    : ${PGWEB_USER:-?} / ${PGWEB_PASS:-?}"
    if [ -n "${TUNNEL_PID:-}" ] && kill -0 "$TUNNEL_PID" 2>/dev/null; then
        say "tunnel   : running (pid $TUNNEL_PID)"
    else
        say "tunnel   : not running"
    fi
    if [ -f "$COMPOSE_FILE" ]; then
        detect_compose
        compose ps || true
    fi
}

# --- argument parsing -------------------------------------------------------
CMD="${1:-}"
[ $# -gt 0 ] && shift || true

case "$CMD" in
    up)
        while [ $# -gt 0 ]; do
            case "$1" in
                --domain)  DOMAIN="${2:-}"; shift 2 ;;
                --quick)   QUICK=1; shift ;;
                --pods)    PODS="${2:-}"; shift 2 ;;
                --lan)     LAN=1; shift ;;
                --user)    PGWEB_USER="${2:-}"; shift 2 ;;
                --pass)    PGWEB_PASS="${2:-}"; shift 2 ;;
                --dry-run) DRY_RUN=1; shift ;;
                --yes|-y)  ASSUME_YES=1; shift ;;
                -h|--help) usage 0 ;;
                http://*|https://*) DOMAIN="$1"; shift ;;
                *.*)       DOMAIN="$1"; shift ;;
                *)         die "unknown option: $1 (try --help)" ;;
            esac
        done
        [ -n "$DOMAIN" ] || [ "$QUICK" -eq 1 ] || \
            die "give a (sub-)domain, e.g. 'up db.example.com', or use 'up --quick'"
        [ "$QUICK" -eq 1 ] || [ -n "$DOMAIN" ] || die "empty domain"
        case "$DOMAIN" in
            http://*|https://*) DOMAIN="${DOMAIN#*://}" ;;
        esac
        DOMAIN="${DOMAIN%%/*}"
        case "$PODS" in ''|*[!0-9]*) die "--pods must be a number" ;; esac
        cmd_up
        ;;
    down)    teardown ;;
    status)  cmd_status ;;
    ""|-h|--help|help) usage 0 ;;
    *)       die "unknown command: $CMD (try --help)" ;;
esac
